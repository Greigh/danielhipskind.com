/**
 * @param {string} name
 * @param {{ size?: number, className?: string, label?: string }} [opts]
 */
export function icon(name, opts = {}) {
  const size = opts.size ?? 16;
  const className = opts.className ? `ui-icon ${opts.className}` : 'ui-icon';
  const paths = PATHS[name] || PATHS.settings;
  const label = opts.label
    ? ` role="img" aria-label="${opts.label}"`
    : ' aria-hidden="true"';
  return `<svg class="${className}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"${label}>${paths}</svg>`;
}

/** Inline icon + optional text for buttons */
export function iconLabel(name, text, opts = {}) {
  return `${icon(name, opts)}${text ? ` ${text}` : ''}`;
}

/** Initials avatar instead of people emoji */
export function initialsAvatar(name, opts = {}) {
  const size = opts.size ?? 28;
  const initials = String(name || '?')
    .split(/\s+/)
    .filter(Boolean)
    .slice(0, 2)
    .map((w) => w[0].toUpperCase())
    .join('');
  return `<span class="avatar-initials" style="--avatar-size:${size}px" aria-hidden="true">${initials}</span>`;
}

/** Priority as a colored dot, not emoji */
export function priorityDot(priority) {
  const p = String(priority || 'medium').toLowerCase();
  return `<span class="priority-dot priority-${p}" title="${p}" aria-label="${p} priority"></span>`;
}

/** Hydrate static HTML: <span data-icon="phone"></span> or data-emoji="📞" */
export function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((el) => {
    if (el.querySelector('svg')) return;
    const name = el.getAttribute('data-icon');
    const size = parseInt(el.getAttribute('data-size') || '16', 10);
    el.innerHTML = icon(name, { size });
  });
  root.querySelectorAll('[data-emoji]').forEach((el) => {
    if (el.querySelector('svg')) return;
    const emoji = el.getAttribute('data-emoji');
    const name = EMOJI_TO_ICON[emoji];
    if (!name) return;
    const size = parseInt(el.getAttribute('data-size') || '16', 10);
    el.innerHTML = icon(name, { size });
  });
}

